// Trasforma un nome in uno slug per l'URL: "Pigiama Lino Blu" -> "pigiama-lino-blu"
export function slugify(name) {
  return name
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}
